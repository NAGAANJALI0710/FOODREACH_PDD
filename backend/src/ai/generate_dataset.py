# Generate rich variations for every base sentence to hit 2500+ training sentences
def generate_rich_dataset():
    rows = []
    seen = set()

    for intent, sentences in intents_data.items():
        for sentence in sentences:
            clean = sentence.strip()
            if clean and (clean.lower(), intent) not in seen:
                seen.add((clean.lower(), intent))
                rows.append((clean, intent))
                
                # Add variations without punctuation if applicable
                if "?" in clean:
                    no_q = clean.replace("?", "").strip()
                    if (no_q.lower(), intent) not in seen:
                        seen.add((no_q.lower(), intent))
                        rows.append((no_q, intent))

    print(f"Generated {len(rows)} sentences across {len(intents_data)} intents.")
    return rows

def main():
    rows = generate_rich_dataset()
    out_dir = os.path.dirname(os.path.abspath(__file__))
    file_path = os.path.join(out_dir, "dataset.csv")
    
    with open(file_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["text", "intent"])
        for text, intent in rows:
            writer.writerow([text, intent])
            
    print(f"Dataset successfully written to {file_path} with {len(rows)} training examples.")

if __name__ == "__main__":
    main()
